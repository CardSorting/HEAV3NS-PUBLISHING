<?php

namespace App\Console;

use App\Services\Moderation\ModerationConfiguration;
use App\Services\Media\AttachmentTranscodingReconciliationService;
use Illuminate\Console\Scheduling\Schedule;
use Illuminate\Foundation\Console\Kernel as ConsoleKernel;

class Kernel extends ConsoleKernel
{
    /**
     * The Artisan commands provided by your application.
     *
     * @var array
     */
    protected $commands = [
        'App\Console\Commands\NpmInstall',
        'App\Console\Commands\CronClearDrafts',
        'App\Console\Commands\CronClearCache',
        'App\Console\Commands\CronEmailExpiringSubs',
        'App\Console\Commands\CronRenewSubscriptions',
        'App\Console\Commands\CronProcessEndingStreams',
        'App\Console\Commands\CronProcessExpiringStreams',
        'App\Console\Commands\CronSendDuePostNotifications',
        'App\Console\Commands\CronProcessUserDeletions',
        'App\Console\Commands\CronReconcileMediaModeration',
        'App\Console\Commands\CronReconcileAttachmentTranscodings',
    ];

    /**
     * Define the application's command schedule.
     *
     * @param  Schedule  $schedule
     * @return void
     */
    protected function schedule(Schedule $schedule)
    {
        $schedule->call([\App\Services\SystemHealthService::class, 'recordSchedulerHeartbeat'])
            ->name('system-health-heartbeat')->everyFiveMinutes();

        // Deleting cached views & cache once in a while, so shared hosting file quota won't go crazy
        $schedule->command('cron:clear_cache_files')->monthly();
        $schedule->command('cron:clear_draft_files')->weekly();
        $schedule->command('manual-payments:prune-documents')->hourly()->withoutOverlapping();
        $schedule->command('queue:work attachment_cleanup --queue=attachment-cleanup --stop-when-empty --max-time=50 --tries=10 --timeout=120')
            ->everyMinute()->withoutOverlapping(10);
        $schedule->command('cron:email_expiring_subs')->daily();
        $schedule->command('users:process-ban-cancellations --limit=10')->everyMinute()->withoutOverlapping(10);
        $schedule->command('cron:renew_subscriptions')->hourly();
        $schedule->command('cron:resetOffers')->daily();
        $schedule->command('cron:process_expiring_streams')->everyFiveMinutes();
        $schedule->command('cron:end_streams')->everyFiveMinutes();
        $schedule->command('cron:send_due_post_notifications')->hourly()->withoutOverlapping();
        $schedule->command('cron:process_user_deletions')->hourly()->withoutOverlapping();
        $schedule->command('conversions:deliver')->everyMinute()->withoutOverlapping(10)
            // Disabled sites only need daily cleanup, not a delivery process every minute.
            ->when(fn () => app(\App\Services\ConversionTracking\ConversionConfiguration::class)->enabled()
                || now()->format('H:i') === '00:00');
        $schedule->command('cron:reconcile_media_moderation')
            ->everyFifteenMinutes()
            ->withoutOverlapping(10)
            ->when(fn () => app(ModerationConfiguration::class)->asyncReconciliationEnabled());
        $schedule->command('cron:reconcile_attachment_transcodings')
            ->everyFifteenMinutes()
            ->withoutOverlapping(10)
            ->when(fn () => app(AttachmentTranscodingReconciliationService::class)->shouldRun());
        $schedule->command('generateSitemap')->daily();
    }

    /**
     * Register the commands for the application.
     *
     * @return void
     */
    protected function commands()
    {
        // Loading commands
        $this->load(__DIR__.'/Commands');

        // Forcing app url rewrite & HTPPS (if needed) on CLI mode
        // In order to get the right urls in the emails generated by the crons
        $url = $this->app['url'];
        $url->forceRootUrl(config('app.url'));
        if(is_int(strpos(config('app.url'), 'https'))){
            \URL::forceScheme('https');
        }

        require base_path('routes/console.php');
    }
}
